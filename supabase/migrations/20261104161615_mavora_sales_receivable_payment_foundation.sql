-- ============================================================
-- MAVORA ERP
-- SALES RECEIVABLE / PAYMENT FOUNDATION
--
-- Outstanding Balance is NOT stored on Customer Master.
--
-- Derived AR:
--   CREDIT Sales grand_total
--   - posted Credit Notes / Returns
--   - posted Payment Allocations
--
-- First AR phase:
--   * exact / partial invoice settlement
--   * one payment may settle multiple invoices
--   * no overpayment
--   * no unallocated advance
--   * no payment reversal
--   * no refund payout
--   * no multi-currency settlement
--
-- Direct authenticated table mutation is prohibited.
-- Controlled RPC is added in the next migration.
-- ============================================================


-- ============================================================
-- 1. CAPABILITIES
-- ============================================================

insert into public.capabilities (
  code,
  module_code,
  action,
  description,
  risk_level,
  is_active
)
values
(
  'sales.receivable_view',
  'sales',
  'receivable_view',
  'View controlled customer Accounts Receivable, invoice balances, Aging and Customer Statements.',
  'standard',
  true
),
(
  'sales.payment_post',
  'sales',
  'payment_post',
  'Post controlled customer payments and allocate them to eligible Credit Sales invoices.',
  'critical',
  true
)
on conflict (code)
do update set
  module_code = excluded.module_code,
  action = excluded.action,
  description = excluded.description,
  risk_level = excluded.risk_level,
  is_active = excluded.is_active;


insert into public.role_capabilities (
  tenant_id,
  role_id,
  capability_code
)
select
  r.tenant_id,
  r.id,
  v.capability_code
from public.roles r
cross join (
  values
    ('sales.receivable_view'::text),
    ('sales.payment_post'::text)
) as v(capability_code)
where upper(r.code) = 'OWNER'
  and r.is_active = true
on conflict (
  role_id,
  capability_code
)
do nothing;


-- ============================================================
-- 2. RECEIVABLE PAYMENT HEADER
-- ============================================================

create table public.sales_receivable_payments (
  id uuid primary key
    default gen_random_uuid(),

  tenant_id uuid not null
    references public.tenants(id)
    on delete restrict,

  site_id uuid not null,

  customer_id uuid not null,

  -- Immutable historical Customer snapshot.
  customer_code_snapshot text not null,

  customer_name_snapshot text not null,

  -- Server-generated by controlled posting RPC.
  receipt_no text not null,

  -- Tenant-scoped idempotency key.
  posting_key text not null,

  -- SHA-256 canonical request fingerprint.
  request_fingerprint text not null,

  payment_method text not null,

  amount numeric(20,6) not null,

  reference_no text,

  note text,

  received_at timestamptz
    not null default now(),

  created_by uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz
    not null default now(),

  constraint
    sales_receivable_payments_site_fk
    foreign key (
      site_id,
      tenant_id
    )
    references public.sites(
      id,
      tenant_id
    )
    on delete restrict,

  constraint
    sales_receivable_payments_customer_fk
    foreign key (
      customer_id,
      tenant_id
    )
    references public.sales_customers(
      id,
      tenant_id
    )
    on delete restrict,

  constraint
    sales_receivable_payments_id_tenant_key
    unique (
      id,
      tenant_id
    ),

  constraint
    sales_receivable_payments_customer_code_check
    check (
      length(
        btrim(
          customer_code_snapshot
        )
      ) between 1 and 120
    ),

  constraint
    sales_receivable_payments_customer_name_check
    check (
      length(
        btrim(
          customer_name_snapshot
        )
      ) between 1 and 255
    ),

  constraint
    sales_receivable_payments_receipt_check
    check (
      length(
        btrim(receipt_no)
      ) between 1 and 120
    ),

  constraint
    sales_receivable_payments_posting_key_check
    check (
      length(
        btrim(posting_key)
      ) between 1 and 120
    ),

  constraint
    sales_receivable_payments_fingerprint_check
    check (
      request_fingerprint
      ~ '^[0-9a-f]{64}$'
    ),

  constraint
    sales_receivable_payments_method_check
    check (
      payment_method in (
        'CASH',
        'BANK',
        'MOBILE',
        'CHEQUE',
        'OTHER'
      )
    ),

  constraint
    sales_receivable_payments_amount_check
    check (
      amount > 0
    ),

  constraint
    sales_receivable_payments_reference_length
    check (
      reference_no is null
      or length(reference_no) <= 255
    ),

  constraint
    sales_receivable_payments_note_length
    check (
      note is null
      or length(note) <= 1000
    ),

  constraint
    sales_receivable_payments_tenant_receipt_key
    unique (
      tenant_id,
      receipt_no
    ),

  constraint
    sales_receivable_payments_tenant_posting_key_key
    unique (
      tenant_id,
      posting_key
    )
);


create index
  sales_receivable_payments_customer_date_idx
on public.sales_receivable_payments (
  tenant_id,
  customer_id,
  received_at desc
);


create index
  sales_receivable_payments_site_date_idx
on public.sales_receivable_payments (
  tenant_id,
  site_id,
  received_at desc
);


-- ============================================================
-- 3. PAYMENT → INVOICE ALLOCATIONS
-- ============================================================

create table public.sales_receivable_allocations (
  id uuid primary key
    default gen_random_uuid(),

  tenant_id uuid not null
    references public.tenants(id)
    on delete restrict,

  payment_id uuid not null,

  sales_order_id uuid not null,

  allocated_amount numeric(20,6)
    not null,

  created_at timestamptz
    not null default now(),

  constraint
    sales_receivable_allocations_payment_fk
    foreign key (
      payment_id,
      tenant_id
    )
    references public.sales_receivable_payments(
      id,
      tenant_id
    )
    on delete restrict,

  constraint
    sales_receivable_allocations_order_fk
    foreign key (
      sales_order_id,
      tenant_id
    )
    references public.sales_orders(
      id,
      tenant_id
    )
    on delete restrict,

  constraint
    sales_receivable_allocations_id_tenant_key
    unique (
      id,
      tenant_id
    ),

  constraint
    sales_receivable_allocations_amount_check
    check (
      allocated_amount > 0
    ),

  constraint
    sales_receivable_allocations_payment_order_key
    unique (
      tenant_id,
      payment_id,
      sales_order_id
    )
);


create index
  sales_receivable_allocations_payment_idx
on public.sales_receivable_allocations (
  tenant_id,
  payment_id
);


create index
  sales_receivable_allocations_order_idx
on public.sales_receivable_allocations (
  tenant_id,
  sales_order_id
);


